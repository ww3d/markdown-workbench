    [ValidateRange(1, [int]::MaxValue)]
    [int] $Issue,

    [string] $Repo,

    [Parameter(Mandatory, ParameterSetName = 'Check')]
    [ValidateNotNullOrEmpty()]
    [string] $Check,

    [Parameter(Mandatory, ParameterSetName = 'Section')]
    [ValidateNotNullOrEmpty()]
    [string] $Section,

    [Parameter(Mandatory, ParameterSetName = 'Section')]
    [AllowEmptyString()]
    [AllowEmptyCollection()]
    [string[]] $Content,

    [Parameter(ParameterSetName = 'Section')]
    [Parameter(ParameterSetName = 'Status')]
    [switch] $Create,
    [Parameter(Mandatory, ParameterSetName = 'Status')]
    [switch] $Status,

    [Parameter(ParameterSetName = 'Status')]
    [ValidateNotNullOrEmpty()]
    [string[]] $Hand,

    [Parameter(Mandatory, ParameterSetName = 'Field')]
    [Parameter(Mandatory, ParameterSetName = 'FieldRemove')]
    [ValidatePattern('^[A-Za-z][A-Za-z0-9 _-]*$')]
    [string] $Field,

    [Parameter(Mandatory, ParameterSetName = 'FieldRemove')]
    [switch] $Remove,

    [Parameter(Mandatory, ParameterSetName = 'Field')]
    [ValidatePattern('^[^\r\n]+$')]
    [string] $Value
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$checklistItems = Join-Path $PSScriptRoot 'get-checklist-items.ps1'
$statusBlock = Join-Path $PSScriptRoot 'get-status-block.ps1'

# The same line split get-checklist-items.ps1 uses, so its Line numbers and
# this script's line list agree.
$lineBreak = "`r?`n"

function Get-LineCount([string] $Text) { @($Text -split $lineBreak).Count }

# The body as pieces that keep their own line ending; joined they give the body
# back byte for byte. A trailing line break leaves no empty piece behind.
function Split-Piece([string] $Text) {
    if ($Text -eq '') { return , @() }
    $pieces = [regex]::Split($Text, '(?<=\n)')
    if ($pieces[-1] -eq '') { $pieces = $pieces[0..($pieces.Count - 2)] }
    , @($pieces)
}

function Get-PieceText([string] $Piece) { $Piece -replace "`r?`n$", '' }

# Read over REST: the body stays one string inside the JSON. invoke-gh.ps1 decodes gh as UTF-8, so no
# non-ASCII character comes back altered and is written back altered.
$invokeGh = Join-Path $PSScriptRoot 'invoke-gh.ps1'
function Invoke-Gh {
    param([string[]] $Argument)
    $reply = & $invokeGh -Argument $Argument
    if ($reply.ExitCode -ne 0) { throw "gh $($Argument[0..1] -join ' ') exited $($reply.ExitCode): $($reply.Error)" }
    ($reply.Output -join "`n") | ConvertFrom-Json
}

function Read-IssueBody([string] $Slug) {
    $answer = Invoke-Gh -Argument @('api', "repos/$Slug/issues/$Issue")
    if ($null -ne $answer.PSObject.Properties['pull_request']) {
        throw "$Slug#$Issue is a pull request, not an issue."
    }
    "$($answer.body)"
}

# The footer the server appends to a body an agent writes - no change of the edit.
$serverFooter = '(?:\r?\n)*---\r?\n_Generated by \[Claude Code\]\(https://claude\.ai/code\)_[ \t]*(?:\r?\n)?$'

function Test-SameBody([string] $Stored, [string] $Sent) {
    $stored = $Stored -replace "`r`n", "`n"
    $sent = $Sent -replace "`r`n", "`n"
    if ($stored -ceq $sent) { return $true }
    $bareStored = $stored -creplace $serverFooter, ''
    $bareSent = $sent -creplace $serverFooter, ''
    $footered = $bareStored.Length -lt $stored.Length -or $bareSent.Length -lt $sent.Length
    $footered -and $bareStored.TrimEnd("`n") -ceq $bareSent.TrimEnd("`n")
}

function Write-IssueBody([string] $Slug, [string] $Body) {
    $file = [System.IO.Path]::GetTempFileName()
    try {
        $json = ConvertTo-Json -InputObject @{ body = $Body } -Compress
        [System.IO.File]::WriteAllText($file, $json, [System.Text.UTF8Encoding]::new($false))
        $answer = Invoke-Gh -Argument @('api', '--method', 'PATCH', "repos/$Slug/issues/$Issue", '--input', $file)
        "$($answer.body)"
    } finally {
        Remove-Item -LiteralPath $file -ErrorAction SilentlyContinue
    }
}

# Per line: is it inside a fenced code block or one of its fence lines? The fence rule of
# get-checklist-items.ps1 (CommonMark: same character, at least as long, nothing but
# whitespace behind a closing fence).
function Get-FenceFlag([string[]] $Lines) {
    $fencePattern = '^\s*(?:>\s*)*(`{3,}|~{3,})(.*)$'
    $openFence = $null
    for ($i = 0; $i -lt $Lines.Count; $i++) {
        if ($Lines[$i] -match $fencePattern) {
            $fence = $Matches[1]
            $rest = $Matches[2]
            if ($null -eq $openFence) { $openFence = $fence }
            elseif ($fence[0] -eq $openFence[0] -and $fence.Length -ge $openFence.Length -and -not $rest.Trim()) {
                $openFence = $null
            }
            $true
            continue
        }
        $null -ne $openFence
    }
}

# Headings outside a fenced code block.
function Get-Heading([string[]] $Lines) {
    $fenced = @(Get-FenceFlag $Lines)
    for ($i = 0; $i -lt $Lines.Count; $i++) {
        $line = $Lines[$i]
        if ($fenced[$i]) { continue }
        if ($line -match '^ {0,3}(#{1,6})(?:[ \t]+(.*?))?(?:[ \t]+#+)?[ \t]*$') {
            [pscustomobject]@{ Index = $i; Level = $Matches[1].Length; Text = "$($Matches[2])".Trim() }
        }
    }
}

# One edit: the pieces [Start, End) give way to $New. Returns the new body
# after checking that everything around the edit is unchanged and the line
# count moved by exactly the lines added minus the lines removed.
function Join-Piece([string[]] $Pieces, [int] $From, [int] $To) {
    if ($To -le $From) { return '' }
    -join $Pieces[$From..($To - 1)]
}

function Get-EditedBody {
    param([string] $Body, [string[]] $Pieces, [int] $Start, [int] $End, [string[]] $New, [string] $Newline)

    $prefix = Join-Piece $Pieces 0 $Start
    $suffix = Join-Piece $Pieces $End $Pieces.Count
    $middle = -join @($New | ForEach-Object { $_ + $Newline })
    # At the end of a body without a final line break, the new last line has none either.
    if ($End -eq $Pieces.Count -and -not $Body.EndsWith("`n")) {
        if ($middle) {
            $middle = $middle.Substring(0, $middle.Length - $Newline.Length)
            if ($prefix -and -not $prefix.EndsWith("`n")) { $prefix += $Newline }
        } else {
            $prefix = $prefix -replace "`r?`n$", ''
        }
    }
    $result = $prefix + $middle + $suffix

    $before = $prefix -replace "`r?`n$", ''
    if (-not $result.StartsWith($before, [StringComparison]::Ordinal) -or
        -not $result.EndsWith($suffix, [StringComparison]::Ordinal) -or
        -not $Body.StartsWith($before, [StringComparison]::Ordinal) -or
        -not $Body.EndsWith($suffix, [StringComparison]::Ordinal)) {
        throw 'the text around the edited place would change - nothing written.'
    }
    # An empty body has no lines at all; Get-LineCount counts its one empty piece.
    $bodyLines = if ($Body -eq '') { 0 } else { Get-LineCount $Body }
    $expected = $bodyLines - ($End - $Start) + $New.Count
    $actual = Get-LineCount $result
    if ($actual -ne $expected) {
        throw "the body would have $actual lines instead of $expected - nothing written."
    }
    $result
}

# The status section of $Text, recomputed. A body without a marker line costs no REST call.
function Get-StatusSectionUpdate([string] $Text) {
    $same = [pscustomobject]@{ Text = $Text; Status = 'none'; Problem = '' }
    if ($Text -notmatch '(?m)^<!--\s*status:begin\b') { return $same }
    $status = & $statusBlock -Body $Text -Repo $slug -Issue $Issue
    if ($status.Result -eq 'broken') { $same.Status = 'broken'; $same.Problem = $status.Problem; return $same }
    if ($status.Result -eq 'absent') { return $same }
    $same.Status = 'unchanged'
    if ($status.Result -eq 'unchanged') { return $same }
    $textPieces = Split-Piece $Text
    $textLines = @($textPieces | ForEach-Object { Get-PieceText $_ })
    $ending = $textPieces[$status.Start].Substring($textLines[$status.Start].Length)
    $same.Text = Get-EditedBody -Body $Text -Pieces $textPieces -Start $status.Start -End ($status.End + 1) -New $status.Lines -Newline $ending
    $same.Status = 'refreshed'
    $same
}

# Lines new to the head of $Text go where the head ends: set off by a blank line before (unless one is there)
# and, in front of the first level-2 heading, behind.
function Add-HeadLine([string] $Text, [string[]] $New, [int] $At) {
    $textPieces = Split-Piece $Text
    $textLines = @($textPieces | ForEach-Object { Get-PieceText $_ })
    $lineNew = @()
    if ($At -gt 0 -and $textLines[$At - 1].Trim()) { $lineNew += '' }
    $lineNew += $New
    if ($At -lt $textLines.Count -and $textLines[$At].Trim()) { $lineNew += '' }
    $nl = if ($Text -match "\r?\n") { $Matches[0] } else { "`n" }
    Get-EditedBody -Body $Text -Pieces $textPieces -Start $At -End $At -New $lineNew -Newline $nl
}

# Where the head of $Text ends, and the alert in it: the line after the alert and its blank line, or the head's end.
function Get-HeadPlace([string] $Text) {
    $textPieces = Split-Piece $Text
    $textLines = @($textPieces | ForEach-Object { Get-PieceText $_ })
    $fencedLine = @(Get-FenceFlag $textLines)
    $h2 = @(Get-Heading $textLines | Where-Object Level -eq 2 | Select-Object -First 1)
    $headEnd = if ($h2) { $h2[0].Index } else { $textLines.Count }
    $alertAt = -1
    for ($i = 0; $i -lt $headEnd; $i++) {
        if (-not $fencedLine[$i] -and $textLines[$i] -cmatch '^>\s*\[!NOTE\]\s*$') { $alertAt = $i; break }
    }
    $after = $headEnd
    if ($alertAt -ge 0) {
        $after = $alertAt + 1
        while ($after -lt $headEnd -and $textLines[$after] -match '^>') { $after++ }
        if ($after -lt $headEnd -and -not $textLines[$after].Trim()) { $after++ }
    }
    [pscustomobject]@{ HeadEnd = $headEnd; HasAlert = $alertAt -ge 0; After = $after }
}

# owner/name from -Repo, or from the checkout's remote over REST - `gh repo
# view` would be a GraphQL call.
$slug = $Repo
if (-not $slug) {
    $slug = "$((Invoke-Gh -Argument @('api', 'repos/{owner}/{repo}')).full_name)"
    if (-not $slug) { throw 'the repository could not be resolved - pass -Repo owner/name.' }
}

$body = Read-IssueBody $slug
$pieces = Split-Piece $body
$lines = @($pieces | ForEach-Object { Get-PieceText $_ })
$newline = if ($body -match "\r?\n") { $Matches[0] } else { "`n" }
$result = [pscustomobject]@{
    Issue       = "$slug#$Issue"
    Action      = $PSCmdlet.ParameterSetName.ToLowerInvariant()
    Line        = 0
    LinesBefore = Get-LineCount $body
    LinesAfter  = Get-LineCount $body
    Removed     = @()
    Added       = @()
    Result      = 'unchanged'
    Status      = 'none'
}

if ($PSCmdlet.ParameterSetName -eq 'Check') {
    $items = @(& $checklistItems -Body $body | Where-Object { $_.Text.Contains($Check, [StringComparison]::Ordinal) })
    $open = @($items | Where-Object { -not $_.Checked })
    if ($open.Count -eq 0 -and @($items | Where-Object Checked).Count -eq 1) {
        $result.Line = @($items | Where-Object Checked)[0].Line
        return $result
    }
    if ($open.Count -ne 1) {
        $found = if ($items) { ($items | ForEach-Object { "line $($_.Line): $($_.Text)" }) -join '; ' } else { 'none' }
        throw "-Check '$Check' must match exactly one unticked checkbox of $slug#$Issue, found $($open.Count) (matches: $found)."
    }
    $start = $open[0].Line - 1
    $stop = $start + 1
    $new = @($lines[$start] -replace '^(\s*(?:>\s*)*(?:[-*+]|\d+[.)])\s*\[) \]', '$1x]')
    # A tick changes one character of its line and nothing else.
    $differing = @(0..($new[0].Length - 1) | Where-Object { $new[0][$_] -cne $lines[$start][$_] })
    if ($new[0].Length -ne $lines[$start].Length -or $differing.Count -ne 1) {
        throw 'a tick would change more than one character - nothing written.'
    }
    $ending = $pieces[$start].Substring($lines[$start].Length)
    $edited = Get-EditedBody -Body $body -Pieces $pieces -Start $start -End $stop -New $new -Newline $ending
} elseif ($PSCmdlet.ParameterSetName -eq 'Status') {
    if ($Hand -and -not $Create) { throw '-Hand needs -Create.' }
    # pwsh -File hands a comma list over as one string: split it before each next bold label.
    if ($Hand) { $Hand = @($Hand | ForEach-Object { $_ -split ',(?=\*\*[^*]+:\*\*)' }) }
    $stated = Get-StatusSectionUpdate $body
    if ($stated.Status -eq 'broken') { throw "$slug#${Issue}: $($stated.Problem) - nothing written." }
    $edited = $stated.Text
    $result.Status = $stated.Status
    if ($stated.Status -eq 'none') {
        if (-not $Create) { throw "$slug#$Issue has no status section - pass -Create to add one, nothing written." }
        $place = Get-HeadPlace $body
        if ($Hand) {
            if ($place.HasAlert) { throw "$slug#$Issue already has an alert in its head - -Hand would add a second one, nothing written." }
            $edited = Add-HeadLine $edited (@('> [!NOTE]') + @($Hand | ForEach-Object { "> - $_" })) $place.HeadEnd
            $place = Get-HeadPlace $edited
        }
        $block = & $statusBlock -Body $edited -Repo $slug -Issue $Issue
        $edited = Add-HeadLine $edited $block.Lines $place.After
        $result.Status = 'created'
    }
    $oldLine = $lines
    $editedPieces = Split-Piece $edited
    $newLine = @($editedPieces | ForEach-Object { Get-PieceText $_ })
    $first = 0
    while ($first -lt $oldLine.Count -and $first -lt $newLine.Count -and $oldLine[$first] -ceq $newLine[$first]) { $first++ }
    $tail = 0
    while ($tail -lt $oldLine.Count - $first -and $tail -lt $newLine.Count - $first -and $oldLine[$oldLine.Count - 1 - $tail] -ceq $newLine[$newLine.Count - 1 - $tail]) { $tail++ }
    $start = $first
    $stop = $oldLine.Count - $tail
    $new = @($newLine | Select-Object -Skip $first -First ($newLine.Count - $first - $tail))
} elseif ($PSCmdlet.ParameterSetName -in 'Field', 'FieldRemove') {
    $fenced = @(Get-FenceFlag $lines)
    $firstH2 = @(Get-Heading $lines | Where-Object Level -eq 2 | Select-Object -First 1)
    $headEnd = if ($firstH2) { $firstH2[0].Index } else { $lines.Count }
    $own = @(0..($headEnd - 1) | Where-Object { $headEnd -gt 0 -and -not $fenced[$_] -and $lines[$_].StartsWith("${Field}:", [StringComparison]::Ordinal) })
    if ($own.Count -gt 1) {
        throw "$slug#$Issue has $($own.Count) '${Field}:' lines in its head (lines $(($own | ForEach-Object { $_ + 1 }) -join ', ')) - nothing written."
    }
    $fieldLine = "${Field}: $Value"
    if ($Remove) {
        # Undoes the insert below: the line and the one blank line that set it off, so no gap stays.
        $start = $stop = 0
        $new = @()
        $edited = $body
        if ($own.Count) {
            $start = $own[0]
            $stop = $start + 1
            if ($stop -lt $lines.Count -and -not $lines[$stop].Trim()) { $stop++ }
            elseif ($start -gt 0 -and -not $lines[$start - 1].Trim()) { $start-- }
            $edited = Get-EditedBody -Body $body -Pieces $pieces -Start $start -End $stop -New $new -Newline $newline
        }
    } elseif ($own.Count -eq 1) {
        $start = $own[0]
        $stop = $start + 1
        $new = @($fieldLine)
        $edited = Get-EditedBody -Body $body -Pieces $pieces -Start $start -End $stop -New $new -Newline $pieces[$start].Substring($lines[$start].Length)
    } else {
        # A paragraph of its own: a blank line before it unless one is there, and one behind it before the heading.
        $start = $stop = $headEnd
        $new = @()
        if ($start -gt 0 -and $lines[$start - 1].Trim()) { $new += '' }
        $new += $fieldLine
        if ($firstH2) { $new += '' }
        $edited = Get-EditedBody -Body $body -Pieces $pieces -Start $start -End $stop -New $new -Newline $newline
    }
} else {
    $name = ($Section -replace '^\s*#+\s*', '').Trim()
    $headings = @(Get-Heading $lines)
    $hits = @($headings | Where-Object Text -ceq $name)
    $appending = $Create -and $hits.Count -eq 0
    if ($hits.Count -ne 1 -and -not $appending) {
        $known = if ($headings) { ($headings | ForEach-Object { "'$($_.Text)'" }) -join ', ' } else { 'none' }
        throw "-Section '$name' must name exactly one heading of $slug#$Issue, found $($hits.Count) (headings: $known)."
    }

    # A trailing line break ends the last line; it adds no empty one.
    $content = @(($Content -join "`n") -split $lineBreak)
    if ($content[-1] -eq '') { $content = @($content | Select-Object -SkipLast 1) }

    if ($appending) {
        # The new section goes to the body's end, set off by one blank line unless the body is empty.
        $start = $stop = $lines.Count
        $new = @()
        if ($lines.Count) { $new += '' }
        $new += "## $name"
        if ($content.Count) { $new += ''; $new += $content }
    } else {
        $heading = $hits[0]
        $next = @($headings | Where-Object { $_.Index -gt $heading.Index -and $_.Level -le $heading.Level } | Select-Object -First 1)
        $end = if ($next) { $next[0].Index } else { $lines.Count }
        # The blank lines right under the heading and right before the next one stay.
        $start = $heading.Index + 1
        while ($start -lt $end -and -not $lines[$start].Trim()) { $start++ }
        $stop = $end
        while ($stop -gt $start -and -not $lines[$stop - 1].Trim()) { $stop-- }
        if ($start -eq $end) { $start = $stop = $heading.Index + 1 }
        $new = $content
    }
    $edited = Get-EditedBody -Body $body -Pieces $pieces -Start $start -End $stop -New $new -Newline $newline
}

if ($PSCmdlet.ParameterSetName -ne 'Status' -and $edited -cne $body) {
    $stated = Get-StatusSectionUpdate $edited
    $edited = $stated.Text
    $result.Status = $stated.Status
    if ($stated.Status -eq 'broken') { Write-Warning "$slug#${Issue}: $($stated.Problem) - the section is left as it is." }
}

$result.Line = $start + 1
$result.Removed = @($lines | Select-Object -Skip $start -First ($stop - $start))
$result.Added = $new
$result.LinesAfter = Get-LineCount $edited
if ($edited -ceq $body) { return $result }

if (-not $PSCmdlet.ShouldProcess("$slug#$Issue", "edit body line $($result.Line) ($($result.Action))")) {
    $result.Result = 'what-if'
    return $result
}

# A body edited since the first read would be overwritten with a stale copy.
if ((Read-IssueBody $slug) -cne $body) {
    throw "$slug#$Issue was edited meanwhile - read it again and rerun; nothing written."
}
$stored = Write-IssueBody $slug $edited
if (-not (Test-SameBody $stored $edited)) {
    # Restore the original only while the stored body is still the one this write made: a body someone else
    # changed since is theirs and stays as it is.
    if ((Read-IssueBody $slug) -cne $stored) {
        throw "GitHub stored a different body for $slug#$Issue than was sent and it was edited again since - nothing is written back."
    }
    $null = Write-IssueBody $slug $body
    throw "GitHub stored a different body for $slug#$Issue than was sent - the original is written back."
}
$result.Result = 'written'
$result
