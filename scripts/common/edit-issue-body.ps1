#Requires -Version 7.6

<#
.SYNOPSIS
    Edit one place of an issue body - tick a checkbox, replace a section or set one
    header field - and leave every other byte as it was.

.DESCRIPTION
    Editing an issue body by hand in PowerShell collapses it: the output of a
    native command such as `gh issue view --json body --jq .body` arrives as an
    array of lines, and a [string] parameter, a -replace or an interpolation
    joins that array with spaces. Uploaded again, the body is one line - no
    checkbox renders, and every checklist reader sees nothing open
    (ww3d/playbook#325). This script is the one path an agent takes instead:

    * The body is read as ONE string, from the REST answer's JSON
      (`gh api repos/{owner}/{repo}/issues/{n}`), never from line output.
    * Exactly one place changes. -Check ticks the one unticked checkbox whose
      text contains the given words, read as get-checklist-items.ps1 reads it;
      -Section replaces what stands under one heading, keeping the heading and
      the blank lines around the content; with -Create, a heading that is
      missing is appended at the body's end first; -Field sets the one line
      `<Name>: <Text>` of the body's head (below), -Field with -Remove takes it out. Everything before and
      after that place is compared byte for byte with the original.
    * The line count is checked: a tick keeps it, a section changes it by
      exactly what was added minus what was removed. Any other count aborts
      before anything is written.
    * The body is read again right before the write and compared as a whole - the
      version guard of every mode; a body edited meanwhile aborts, so a parallel
      edit is not overwritten. The window between that read and the write stays -
      GitHub offers no conditional write on issues.
    * A body with a status section (`<!-- status:begin v1 ... -->` to
      `<!-- status:end -->`, get-status-block.ps1) has that section recomputed in the
      same write, whatever the mode; outside the intended place and the section every
      byte stays, and the line count may move by the section's own delta only.
      -Status refreshes the section alone and writes nothing where only `As of` would
      change; -Status -Create adds the section (and with -Hand the alert above it) to a
      body that has none. A broken marker pair is reported as a warning and leaves the
      section alone; -Status then throws.
    * The write sends the body as a JSON file (`gh api --method PATCH --input`),
      so no argument or pipeline can join it. The body GitHub answers with is
      compared with the one sent (line endings aside); a mismatch writes the
      original back and exits 1 - only while the stored body is still the one this write
      made; a body edited again since is left as it is (exit 1, nothing written back).
      The one difference let through is the footer
      `_Generated by [Claude Code](https://claude.ai/code)_` that the server
      sets at the end of a body an agent writes, together with the blank lines
      around it.

    The head of a body is what stands before its first level-2 heading outside a code
    fence. -Field replaces the one line of the head, outside a code fence, that starts
    with `<Name>:`; with none, the line is inserted as a paragraph of its own directly
    before that heading (at the end of a body without one); two such lines abort the
    run without writing. -Remove deletes that line and the blank line that set it off;
    with no such line nothing changes. The plan rule's `Rank:` line is set this way
    (the controller-mode skill, "Planung").

    Line endings are kept per line; new lines take the body's own. Issues go
    over REST only (why: .agents/rules/pr.md "Forge Tooling").
    -WhatIf shows the change without writing.

    This script is deliberately SELF-CONTAINED - it imports no module, because
    it is mirrored into every consumer via scripts/common/. It calls one
    sibling, get-checklist-items.ps1, for the checkbox reading every script in
    this directory shares.

.PARAMETER Issue
    The issue number.

.PARAMETER Repo
    owner/name of the repository. Defaults to the checkout's repository,
    resolved over REST.

.PARAMETER Check
    Words the checkbox text contains (ordinal, case-sensitive). Exactly one
    unticked checkbox must match. If none does but exactly one ticked one does,
    nothing is written and the run succeeds - ticking twice is no error.

.PARAMETER Section
    The heading text of the section to replace, without the leading `#`
    (a leading `#` run is stripped). Exactly one heading outside a code fence
    must carry it. The section runs to the next heading of the same or a higher
    level, or to the end of the body.

.PARAMETER Content
    The new content of -Section, without its heading. A string array is joined
    with line breaks, never with spaces, so a native command's line output can
    be passed as it is. An empty value empties the section.

.PARAMETER Field
    The name of the head field, without the colon: letters, digits, space, `-` and `_`.

.PARAMETER Value
    The text of -Field, one line, not empty.

.PARAMETER Remove
    With -Field: removes the line instead of setting it.

.PARAMETER Status
    Refresh the status section of the body (get-status-block.ps1) and nothing else.

.PARAMETER Hand
    Only with -Status -Create: the bullets of the alert (`> [!NOTE]`) to add above the new
    section, for example `'**Summary:** ...'`. A head that already has an alert aborts the run.
    A comma list that arrives as one string (`pwsh -File`) is split before each next `**Label:**`.

.PARAMETER Create
    With -Status: add the section when the body has none. Otherwise only with -Section.
    When no heading outside a code fence carries the name,
    append one at the end of the body - a blank line (none in an empty body),
    `## <Section>`, a blank line and the content, in the body's own line
    ending. With exactly one such heading the run is the one without -Create;
    with two or more it throws as before.

.INPUTS
    None.

.OUTPUTS
    [pscustomobject] with Issue (owner/repo#N), Action ('check' / 'section' / 'field' / 'status'),
    Line (1-based, first changed line), LinesBefore, LinesAfter, Removed and
    Added (the changed lines), and Result: 'written', 'unchanged' (nothing to
    do) or 'what-if', and Status of the status section: 'none' (the body has none),
    'unchanged', 'refreshed', 'created' or 'broken'.

.EXAMPLE
    ./scripts/common/edit-issue-body.ps1 -Issue 325 -Check 'Hilfsskript im Repo-Tooling'

    Ticks the one open checkbox of ww3d/playbook#325 that contains those words.

.EXAMPLE
    ./scripts/common/edit-issue-body.ps1 -Repo ww3d/playbook -Issue 210 -Section 'Open points' `
        -Content (Get-Content open-points.md) -WhatIf

    Shows how the tracking issue section "Open points" would change, without
    writing.

.EXAMPLE
    ./scripts/common/edit-issue-body.ps1 -Issue 491 -Field Rank -Value 2.5

    Sets the `Rank: 2.5` line in the head of the body, inserting it before the first
    level-2 heading when the body has none.

.EXAMPLE
    ./scripts/common/edit-issue-body.ps1 -Issue 528 -Section 'Seats' -Create -Content 'Seat: ctrl-<repo>'

    Writes the line under `## Seats`, appending that section to the body when
    the issue has none yet.
#>

